import Foundation

/// Одно событие журнала. Ключи короткие намеренно: события хранятся вечно,
/// и каждый лишний байт в строке умножается на годы использования.
///
/// В событии нет ни имён файлов, ни путей, ни содержимого — только числа.
struct AnalyticsEvent: Codable {
    enum Kind: String, Codable {
        /// Показ шторки целиком: пишется в момент закрытия, но временем
        /// события остаётся момент открытия.
        case panel = "p"
        case copy = "c"
        case drag = "d"
    }

    let kind: Kind
    let time: Date
    /// Сколько изображений участвовало — в копировании или в перетаскивании.
    var count: Int?
    /// Позиция миниатюры в карусели, по которой кликнули.
    var index: Int?
    /// Для `panel` — сколько шторка провисела на экране; для `copy` — сколько
    /// прошло от появления шторки до клика.
    var seconds: Double?
    /// Для `panel` — закончился ли показ действием; для `drag` — принял ли
    /// приёмник файлы (или перетаскивание бросили в пустоту).
    var ok: Bool?

    enum CodingKeys: String, CodingKey {
        case kind = "e"
        case time = "t"
        case count = "n"
        case index = "i"
        case seconds = "s"
        case ok
    }
}
